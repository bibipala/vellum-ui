/**
 * Storybook 故事（`stories/generated/`）：每个组件一个文件，故事是它的示例；页面配方一个文件。
 */
import type { ComponentDoc, RecipeDoc } from '../model.ts'
import { RECIPE_SUFFIX } from '../program.ts'

/**
 * 生成文件中的字符串字面量，与 Biome 的格式化结果一致：默认单引号，内容中的单引号多于双引号时用双引号。
 */
function literal(s: string): string {
  const singles = (s.match(/'/g) ?? []).length
  const doubles = (s.match(/"/g) ?? []).length
  const q = singles > doubles ? '"' : "'"
  const body = s.replace(/\\/g, '\\\\').replace(new RegExp(q, 'g'), `\\${q}`)
  return `${q}${body}${q}`
}

export function story(c: ComponentDoc): string {
  const lines = [
    '// Generated by scripts/docs.ts, do not edit',
    "import type { Meta, StoryObj } from '@storybook/react-vite'",
    `import * as ex from '../../examples/${c.name}.examples.tsx'`,
    '',
    // 示例的标题与说明由 .storybook/preview.tsx 按工具栏的语言从 components.json 读取，这里只记组件名与示例名
    // （Storybook 深合并 meta 与故事的 parameters）
    'const meta = {',
    `  title: '${c.category.en}/${c.name}',`,
    `  parameters: { example: { component: '${c.name}' } },`,
    '} satisfies Meta',
    'export default meta',
    '',
  ]
  for (const e of c.examples)
    lines.push(
      `export const ${e.name}: StoryObj = {`,
      `  name: ${literal(e.title.en)},`,
      `  parameters: { example: { name: '${e.name}' } },`,
      `  render: () => <ex.${e.name} />,`,
      '}',
    )
  return `${lines.join('\n')}\n`
}

/** 页面配方的故事：一个文件，每个配方一个故事，放在 App 中。 */
export function recipeStories(recipes: readonly RecipeDoc[]): string {
  const lines = [
    '// Generated by scripts/docs.ts, do not edit',
    "import type { Meta, StoryObj } from '@storybook/react-vite'",
    "import { App } from 'vellum-ui'",
    // 导入按名称排序（与格式化工具一致）；故事按配方的顺序（先入门、后进阶、最后场景）
    ...[...recipes]
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((r) => `import { ${r.name} } from '../../examples/recipes/${r.name}${RECIPE_SUFFIX}'`),
    '',
    "const meta = { title: 'Recipes', parameters: { layout: 'fullscreen' } } satisfies Meta",
    'export default meta',
    '',
    'const frame = {',
    "  display: 'flex',",
    "  flexDirection: 'column',",
    "  boxSizing: 'border-box',",
    "  height: '100dvh',",
    "  overflow: 'auto',",
    "  padding: 'var(--vl-space-5)',",
    "  background: 'var(--vl-color-bg-canvas)',",
    '} as const',
    '',
  ]
  for (const r of recipes)
    lines.push(
      `export const ${r.name}Recipe: StoryObj = {`,
      `  name: ${literal(r.title.en)},`,
      // 配方是完整的页面，与真实页面一样放在 App 中（useMessage、useConfirmDanger 需要它）。外面一层占满窗口高度的
      // 纵向弹性容器（与文档站的预览区相同）：`Page fill`、SplitView 用 height: 100% 占满，没有它们会塌成 0 高
      `  render: () => (`,
      '    <App>',
      '      <div style={frame}>',
      `        <${r.name} />`,
      '      </div>',
      '    </App>',
      '  ),',
      '}',
    )
  return `${lines.join('\n')}\n`
}
