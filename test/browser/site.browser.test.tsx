/**
 * The documentation site (site/) in a real browser: the root component at a few routes (the overview, a component
 * page with a live example, an API page, the tokens page), links of the Markdown rewritten to routes, the language
 * switch, the focus after navigating, search with `Mod+K`, and the color mode saved on this device.
 *
 * The site has its own ThemeProvider and App, so it is mounted here directly rather than through render(). Nothing
 * may log an error or a warning.
 */
import { createRoot, type Root } from 'react-dom/client'
import { afterEach, beforeEach, describe, expect, it, type MockInstance, vi } from 'vitest'
import { SiteRoot } from '../../site/Site.tsx'
import { focused, inAct, page, userEvent } from './render.tsx'

/** Markdown and the examples load their code on first use. */
const WAIT = { timeout: 8000 }

let mounted: { root: Root; container: HTMLElement } | null = null

// No errors or warnings from React, Ant Design or the library while the site renders and navigates
let error: MockInstance
let warn: MockInstance
beforeEach(() => {
  error = vi.spyOn(console, 'error')
  warn = vi.spyOn(console, 'warn')
})

async function openSite(hash: string) {
  history.replaceState(null, '', hash)
  const container = document.createElement('div')
  document.body.appendChild(container)
  const root = createRoot(container)
  mounted = { root, container }
  await inAct(() => root.render(<SiteRoot />))
  return container
}

afterEach(async () => {
  if (mounted) {
    const { root, container } = mounted
    mounted = null
    await inAct(() => root.unmount())
    container.remove()
  }
  history.replaceState(null, '', location.pathname + location.search)
  localStorage.clear()
  document.title = ''
  const logged = [...error.mock.calls, ...warn.mock.calls]
  vi.restoreAllMocks()
  expect(logged).toEqual([])
})

const pageTitle = (name: string) => page.getByRole('heading', { level: 1, name })

describe('documentation site', () => {
  it('home: the overview with links to the component pages, and the landmarks of the frame', async () => {
    await openSite('#/en')
    await expect.element(pageTitle('Components')).toBeVisible()
    expect(document.title).toBe('vellum-ui')
    expect(document.documentElement.lang).toBe('en')
    await expect.element(page.getByRole('banner')).toBeVisible()
    await expect.element(page.getByRole('navigation', { name: 'Documentation' })).toBeVisible()
    await expect.element(page.getByRole('main')).toBeVisible()
    // `components/Box.md` in the Markdown → the route of the page; `../../README.md` → the published file
    const main = page.getByRole('main')
    await expect
      .element(main.getByRole('link', { name: 'Box', exact: true }), WAIT)
      .toHaveAttribute('href', '#/en/components/Box')
    await expect
      .element(main.getByRole('link', { name: 'README' }))
      .toHaveAttribute('href', 'README.md')
  })

  it('a component page: live examples, their code, props and the page title', async () => {
    await openSite('#/en/components/Button')
    await expect.element(pageTitle('Button')).toBeVisible()
    expect(document.title).toBe('Button · vellum-ui')
    const basic = page.getByTestId('example-Basic')
    await expect.element(basic.getByRole('button', { name: 'Save' }), WAIT).toBeVisible()
    await userEvent.click(basic.getByRole('button', { name: 'Show code' }))
    await expect.element(basic.getByText('export function Basic()', { exact: false })).toBeVisible()
    await expect.element(page.getByRole('table', { name: 'Props' })).toBeVisible()
    await expect.element(page.getByRole('cell', { name: 'variant', exact: true })).toBeVisible()
    await expect
      .element(page.getByText('Does not accept style or className', { exact: false }))
      .toBeVisible()
  })

  it('an API page: Markdown with the exports as headings', async () => {
    await openSite('#/en/api/theme')
    await expect.element(pageTitle('Theme')).toBeVisible()
    await expect
      .element(page.getByRole('heading', { level: 2, name: 'extendTheme' }), WAIT)
      .toBeVisible()
    // The generated header and the language switch of the file are not shown
    await expect.element(page.getByText('Generated by', { exact: false })).not.toBeInTheDocument()
    await expect
      .element(page.getByRole('main').getByRole('link', { name: '简体中文' }))
      .not.toBeInTheDocument()
  })

  it('the tokens page: tables of tokens, a link to a guide rewritten to its route', async () => {
    await openSite('#/en/tokens')
    await expect.element(pageTitle('Design tokens')).toBeVisible()
    await expect.element(page.getByRole('cell', { name: 'color-bg-canvas' }), WAIT).toBeVisible()
    await expect
      .element(page.getByRole('link', { name: 'custom styles' }))
      .toHaveAttribute('href', '#/en/guides/custom-styles')
  })

  it('switching the language shows the same page in the other language and keeps the choice', async () => {
    await openSite('#/en/tokens')
    await expect.element(pageTitle('Design tokens')).toBeVisible()
    // The radio buttons of Segmented are hidden; their labels are clicked
    await userEvent.click(page.getByRole('radiogroup', { name: 'Language' }).getByText('简体中文'))
    await expect.element(pageTitle('设计令牌')).toBeVisible()
    expect(location.hash).toBe('#/zh/tokens')
    expect(document.documentElement.lang).toBe('zh-CN')
    expect(document.title).toBe('设计令牌 · vellum-ui')
    await expect.element(page.getByRole('navigation', { name: '文档' })).toBeVisible()
    expect(localStorage.getItem('vellum-ui-docs:lang')).toBe('zh')
  })

  it('a link without a language opens in the saved language', async () => {
    localStorage.setItem('vellum-ui-docs:lang', 'zh')
    await openSite('#/components/Select')
    await expect.element(pageTitle('Select')).toBeVisible()
    await expect.poll(() => location.hash).toBe('#/zh/components/Select')
    await expect.element(page.getByRole('heading', { level: 2, name: '引入' })).toBeVisible()
  })

  it('navigating with the sidebar moves the focus to the page title; arrow keys move within the sidebar', async () => {
    await openSite('#/en')
    await expect.element(pageTitle('Components')).toBeVisible()
    const nav = page.getByRole('navigation', { name: 'Documentation' })
    await userEvent.click(nav.getByRole('button', { name: 'Stack', exact: true }))
    await expect.element(pageTitle('Stack')).toBeVisible()
    expect(location.hash).toBe('#/en/components/Stack')
    await expect.poll(() => focused()).toBe(pageTitle('Stack').element())
    // ↓ from the current entry focuses the next one
    const stack = nav.getByRole('button', { name: 'Stack', exact: true })
    ;(stack.element() as HTMLElement).focus()
    await userEvent.keyboard('{ArrowDown}')
    expect(focused()).toBe(nav.getByRole('button', { name: 'Text', exact: true }).element())
    await userEvent.keyboard('{Home}')
    expect(focused()).toBe(nav.getByRole('button', { name: 'Overview' }).element())
  })

  it('Mod+K opens the search; an export of the API reference opens its page', async () => {
    await openSite('#/en')
    await expect.element(pageTitle('Components')).toBeVisible()
    await userEvent.keyboard('{Control>}k{/Control}')
    const search = page.getByRole('combobox', { name: 'Search' })
    await expect.element(search).toBeVisible()
    await userEvent.type(search, 'extendTheme')
    await userEvent.keyboard('{Enter}')
    await expect.element(pageTitle('Theme')).toBeVisible()
    expect(location.hash).toBe('#/en/api/theme#extendtheme')
    await expect
      .poll(() => (focused() as HTMLElement | null)?.textContent, WAIT)
      .toBe('extendTheme')
  })

  it('color mode and density are chosen in the appearance menu and saved on this device', async () => {
    await openSite('#/en')
    await expect.element(pageTitle('Components')).toBeVisible()
    await userEvent.click(page.getByRole('button', { name: /^Appearance/ }))
    await userEvent.click(page.getByRole('menuitem', { name: 'Dark' }))
    await expect.poll(() => document.documentElement.dataset.vlMode).toBe('dark')
    expect(localStorage.getItem('vellum-ui-docs:color-mode')).toBe('dark')
    await userEvent.click(page.getByRole('button', { name: /^Appearance/ }))
    await userEvent.click(page.getByRole('menuitem', { name: 'Compact' }))
    await expect.poll(() => document.documentElement.dataset.vlDensity).toBe('compact')
    expect(localStorage.getItem('vellum-ui-docs:density')).toBe('compact')
  })

  it('an unknown address shows "not found" with a way back', async () => {
    await openSite('#/en/components/NoSuchThing')
    await expect.element(pageTitle('Page not found')).toBeVisible()
    await expect
      .element(page.getByRole('link', { name: 'Go to the overview' }))
      .toHaveAttribute('href', '#/en')
  })
})
